UMaterialInterface* LoadBaseMaterial(const TCHAR* Path)
{
	if (UMaterialInterface* M = LoadObject<UMaterialInterface>(nullptr, Path))
	{
		return M;
	}
	static bool bWarned = false;
	if (!bWarned)
	{
		bWarned = true;
		UE_LOG(LogSkyLine, Error, TEXT("Aircraft base material %s is missing. Open the project in the editor once so "
			"Content/Python/init_unreal.py can create it. Falling back to the default material."), Path);
	}
	return UMaterial::GetDefaultMaterial(MD_Surface);
}

struct FGlb
{
	TArray<uint8> File;
	TSharedPtr<FJsonObject> Json;
	const uint8* Bin = nullptr;
	int64 BinSize = 0;

	const TArray<TSharedPtr<FJsonValue>>& Arr(const TCHAR* Field) const
	{
		static const TArray<TSharedPtr<FJsonValue>> Empty;
		const TArray<TSharedPtr<FJsonValue>>* A = nullptr;
		return Json->TryGetArrayField(Field, A) ? *A : Empty;
	}

	bool View(int32 ViewIndex, const uint8*& OutData, int64& OutSize) const
	{
		const TArray<TSharedPtr<FJsonValue>>& Views = Arr(TEXT("bufferViews"));
		if (!Views.IsValidIndex(ViewIndex))
		{
			return false;
		}
		const TSharedPtr<FJsonObject> V = Views[ViewIndex]->AsObject();
		const int64 Offset = static_cast<int64>(V->GetNumberField(TEXT("byteOffset")));
		OutSize = static_cast<int64>(V->GetNumberField(TEXT("byteLength")));
		if (Offset < 0 || Offset + OutSize > BinSize)
		{
			return false;
		}
		OutData = Bin + Offset;
		return true;
	}

	/** Accessor data as a typed pointer (our writer emits tightly packed float32 / uint32 data). */
	template <typename T>
	const T* Accessor(int32 Index, int32& OutCount) const
	{
		const TArray<TSharedPtr<FJsonValue>>& Accs = Arr(TEXT("accessors"));
		if (!Accs.IsValidIndex(Index))
		{
			return nullptr;
		}
		const TSharedPtr<FJsonObject> A = Accs[Index]->AsObject();
		const uint8* Data = nullptr;
		int64 Size = 0;
		if (!View(static_cast<int32>(A->GetNumberField(TEXT("bufferView"))), Data, Size))
		{
			return nullptr;
		}
		OutCount = static_cast<int32>(A->GetNumberField(TEXT("count")));
		return reinterpret_cast<const T*>(Data);
	}

	bool Parse(FString& OutError)
	{
		if (File.Num() < 20 || *reinterpret_cast<const uint32*>(File.GetData()) != 0x46546C67u)
		{
			OutError = TEXT("not a GLB file");
			return false;
		}
		const uint32 JsonLen = *reinterpret_cast<const uint32*>(File.GetData() + 12);
		const FUTF8ToTCHAR Conv(reinterpret_cast<const ANSICHAR*>(File.GetData() + 20), JsonLen);
		const FString Text(Conv.Length(), Conv.Get());
		const TSharedRef<TJsonReader<>> Reader = TJsonReaderFactory<>::Create(Text);
		if (!FJsonSerializer::Deserialize(Reader, Json) || !Json.IsValid())
		{
			OutError = TEXT("bad GLB JSON chunk");
			return false;
		}
		const int64 BinHeader = 20 + static_cast<int64>(JsonLen);
		if (BinHeader + 8 <= File.Num())
		{
			BinSize = *reinterpret_cast<const uint32*>(File.GetData() + BinHeader);
			Bin = File.GetData() + BinHeader + 8;
			BinSize = FMath::Min<int64>(BinSize, File.Num() - BinHeader - 8);
		}
		return true;
	}
};

struct FDecodedImage
{
	int32 Width = 0, Height = 0;
	TArray<TArray64<uint8>> Mips;  // BGRA8
};

/** Thread-safe once the module is loaded (load it on the game thread first). */
bool DecodeImage(IImageWrapperModule& Module, const uint8* Data, int64 Size, FDecodedImage& Out)
{
	const EImageFormat Format = Module.DetectImageFormat(Data, Size);
	if (Format == EImageFormat::Invalid)
	{
		return false;
	}
	const TSharedPtr<IImageWrapper> Wrapper = Module.CreateImageWrapper(Format);
	if (!Wrapper.IsValid() || !Wrapper->SetCompressed(Data, Size))
	{
		return false;
	}
	TArray64<uint8> Raw;
	if (!Wrapper->GetRaw(ERGBFormat::BGRA, 8, Raw))
	{
		return false;
	}
	Out.Width = static_cast<int32>(Wrapper->GetWidth());
	Out.Height = static_cast<int32>(Wrapper->GetHeight());
	Out.Mips.Add(MoveTemp(Raw));
	// Box-filtered mip chain (aircraft textures are viewed at every distance).
	int32 W = Out.Width, H = Out.Height;
	while (W > 1 || H > 1)
	{
		const int32 NW = FMath::Max(1, W / 2), NH = FMath::Max(1, H / 2);
		const TArray64<uint8>& Src = Out.Mips.Last();
		TArray64<uint8> Dst;
		Dst.SetNumUninitialized(static_cast<int64>(NW) * NH * 4);
		for (int32 Y = 0; Y < NH; Y++)
		{
			const int32 Y0 = FMath::Min(Y * 2, H - 1), Y1 = FMath::Min(Y * 2 + 1, H - 1);
			for (int32 X = 0; X < NW; X++)
			{
				const int32 X0 = FMath::Min(X * 2, W - 1), X1 = FMath::Min(X * 2 + 1, W - 1);
				for (int32 C = 0; C < 4; C++)
				{
					const int32 Sum = Src[(static_cast<int64>(Y0) * W + X0) * 4 + C] + Src[(static_cast<int64>(Y0) * W + X1) * 4 + C] +
						Src[(static_cast<int64>(Y1) * W + X0) * 4 + C] + Src[(static_cast<int64>(Y1) * W + X1) * 4 + C];
					Dst[(static_cast<int64>(Y) * NW + X) * 4 + C] = static_cast<uint8>((Sum + 2) / 4);
				}
			}
		}
		Out.Mips.Add(MoveTemp(Dst));
		W = NW;
		H = NH;
	}
	return true;
}

UTexture2D* MakeTexture(FDecodedImage& Img, bool bSRGB, FName Name)
{
	UTexture2D* Tex = UTexture2D::CreateTransient(Img.Width, Img.Height, PF_B8G8R8A8, Name);
	if (!Tex)
	{
		return nullptr;
	}
	FTexturePlatformData* PD = Tex->GetPlatformData();
	for (int32 Level = 0; Level < Img.Mips.Num(); Level++)
	{
		FTexture2DMipMap* Mip = nullptr;
		if (Level == 0)
		{
			Mip = &PD->Mips[0];
		}
		else
		{
			Mip = new FTexture2DMipMap();
			Mip->SizeX = FMath::Max(1, Img.Width >> Level);
			Mip->SizeY = FMath::Max(1, Img.Height >> Level);
			Mip->SizeZ = 1;
			PD->Mips.Add(Mip);
		}
		Mip->BulkData.Lock(LOCK_READ_WRITE);
		void* Dest = Mip->BulkData.Realloc(Img.Mips[Level].Num());
		FMemory::Memcpy(Dest, Img.Mips[Level].GetData(), Img.Mips[Level].Num());
		Mip->BulkData.Unlock();
	}
	Tex->SRGB = bSRGB;
	Tex->Filter = TF_Trilinear;
	Tex->AddressX = TA_Wrap;
	Tex->AddressY = TA_Wrap;
	Tex->LODGroup = TEXTUREGROUP_World;
	Tex->UpdateResource();
	return Tex;
}

struct FMaterialDef
{
	FName Name;
	FLinearColor BaseColor = FLinearColor::White;
	int32 Texture = INDEX_NONE;
	float Roughness = 0.6f;
	float Metallic = 0.f;
	FLinearColor Emissive = FLinearColor::Black;
	FString AlphaMode = TEXT("OPAQUE");
	bool bDoubleSided = false;
};

FLinearColor ReadColor(const TSharedPtr<FJsonObject>& Obj, const TCHAR* Field, const FLinearColor& Default)
{
	const TArray<TSharedPtr<FJsonValue>>* A = nullptr;
	if (!Obj->TryGetArrayField(Field, A) || A->Num() < 3)
	{
		return Default;
	}
	return FLinearColor((*A)[0]->AsNumber(), (*A)[1]->AsNumber(), (*A)[2]->AsNumber(), A->Num() > 3 ? (*A)[3]->AsNumber() : 1.0);
}

UStaticMesh* BuildMesh(const FGlb& Glb, const TSharedPtr<FJsonObject>& MeshJson, const TArray<UMaterialInterface*>& Materials,
	const TArray<FMaterialDef>& Defs, UObject* Outer, FName Name)
{
	FMeshDescription MD;
	FStaticMeshAttributes Attr(MD);
	Attr.Register();
	TVertexAttributesRef<FVector3f> Positions = Attr.GetVertexPositions();
	TVertexInstanceAttributesRef<FVector3f> Normals = Attr.GetVertexInstanceNormals();
	TVertexInstanceAttributesRef<FVector3f> Tangents = Attr.GetVertexInstanceTangents();
	TVertexInstanceAttributesRef<float> Signs = Attr.GetVertexInstanceBinormalSigns();
	TVertexInstanceAttributesRef<FVector2f> UVs = Attr.GetVertexInstanceUVs();
	TPolygonGroupAttributesRef<FName> SlotNames = Attr.GetPolygonGroupMaterialSlotNames();
	UVs.SetNumChannels(1);
	const bool bFlip = CVarFlipWinding.GetValueOnGameThread() != 0;

	UStaticMesh* Mesh = NewObject<UStaticMesh>(Outer, Name, RF_Transient);
	const TArray<TSharedPtr<FJsonValue>>* Prims = nullptr;
	if (!MeshJson->TryGetArrayField(TEXT("primitives"), Prims))
	{
		return nullptr;
	}
	for (const TSharedPtr<FJsonValue>& PrimV : *Prims)
	{
		const TSharedPtr<FJsonObject> Prim = PrimV->AsObject();
		const TSharedPtr<FJsonObject> Attrs = Prim->GetObjectField(TEXT("attributes"));
		int32 NP = 0, NN = 0, NT = 0, NI = 0;
		const float* P = Glb.Accessor<float>(static_cast<int32>(Attrs->GetNumberField(TEXT("POSITION"))), NP);
		const float* N = Glb.Accessor<float>(static_cast<int32>(Attrs->GetNumberField(TEXT("NORMAL"))), NN);
		const float* T = Glb.Accessor<float>(static_cast<int32>(Attrs->GetNumberField(TEXT("TEXCOORD_0"))), NT);
		const uint32* I = Glb.Accessor<uint32>(static_cast<int32>(Prim->GetNumberField(TEXT("indices"))), NI);
		if (!P || !N || !T || !I || NN != NP || NT != NP)
		{
			continue;
		}
		const int32 MatIndex = static_cast<int32>(Prim->GetNumberField(TEXT("material")));
		const FName SlotName = Defs.IsValidIndex(MatIndex) ? Defs[MatIndex].Name : FName(TEXT("Default"));
		const FPolygonGroupID Group = MD.CreatePolygonGroup();
		SlotNames[Group] = SlotName;
		Mesh->GetStaticMaterials().Add(FStaticMaterial(Materials.IsValidIndex(MatIndex) ? Materials[MatIndex] : nullptr, SlotName, SlotName));

		TArray<FVertexInstanceID> Inst;
		Inst.SetNumUninitialized(NP);
		for (int32 V = 0; V < NP; V++)
		{
			const FVertexID Vid = MD.CreateVertex();
			// glTF (m, +Y up, +Z nose, +X left) -> Unreal (cm, X nose, Y right, Z up)
			Positions[Vid] = FVector3f(P[V * 3 + 2], -P[V * 3], P[V * 3 + 1]) * 100.f;
			const FVertexInstanceID Vi = MD.CreateVertexInstance(Vid);
			const FVector3f Nrm(N[V * 3 + 2], -N[V * 3], N[V * 3 + 1]);
			Normals[Vi] = Nrm;
			const FVector3f Ref = FMath::Abs(Nrm.Z) < 0.9f ? FVector3f(0, 0, 1) : FVector3f(1, 0, 0);
			Tangents[Vi] = FVector3f::CrossProduct(Ref, Nrm).GetSafeNormal();
			Signs[Vi] = 1.f;
			UVs.Set(Vi, 0, FVector2f(T[V * 2], T[V * 2 + 1]));
			Inst[V] = Vi;
		}
		for (int32 K = 0; K + 2 < NI; K += 3)
		{
			const uint32 A = I[K], B = I[K + 1], C = I[K + 2];
			if (A == B || B == C || A == C || A >= static_cast<uint32>(NP) || B >= static_cast<uint32>(NP) || C >= static_cast<uint32>(NP))
			{
				continue;
			}
			FVertexInstanceID Tri[3] = {Inst[A], bFlip ? Inst[C] : Inst[B], bFlip ? Inst[B] : Inst[C]};
			MD.CreateTriangle(Group, MakeArrayView(Tri, 3));
		}
	}
	if (Mesh->GetStaticMaterials().Num() == 0)
	{
		return nullptr;
	}
	UStaticMesh::FBuildMeshDescriptionsParams Params;
	Params.bFastBuild = true;
	Params.bBuildSimpleCollision = false;
	Params.bCommitMeshDescription = false;
	Params.bMarkPackageDirty = false;
	Params.bAllowCpuAccess = false;
	TArray<const FMeshDescription*> List;
	List.Add(&MD);
	Mesh->BuildFromMeshDescriptions(List, Params);
	return Mesh;
}

