UTexture2D* FAircraftModelLoader::CreateTexture(const uint8* Data, int64 Size, bool bSRGB, UObject* Outer, FName Name)
{
	FDecodedImage Img;
	IImageWrapperModule& Module = FModuleManager::LoadModuleChecked<IImageWrapperModule>(TEXT("ImageWrapper"));
	if (!DecodeImage(Module, Data, Size, Img))
	{
		return nullptr;
	}
	return MakeTexture(Img, bSRGB, Name);
}

UTexture2D* FAircraftModelLoader::LoadTextureFile(const FString& Path, bool bSRGB, UObject* Outer)
{
	TArray<uint8> Bytes;
	if (!FFileHelper::LoadFileToArray(Bytes, *Path))
	{
		UE_LOG(LogSkyLine, Warning, TEXT("Missing texture %s"), *Path);
		return nullptr;
	}
	return CreateTexture(Bytes.GetData(), Bytes.Num(), bSRGB, Outer, NAME_None);
}

bool FAircraftModelLoader::Load(const FSkyLineAircraftEntry& Entry, UObject* Outer, FSkyLineAircraftModel& Out, FString& OutError)
{
	const double T0 = FPlatformTime::Seconds();
	FGlb Glb;
	if (!FFileHelper::LoadFileToArray(Glb.File, *Entry.GlbPath))
	{
		OutError = FString::Printf(TEXT("cannot read %s"), *Entry.GlbPath);
		return false;
	}
	if (!Glb.Parse(OutError))
	{
		return false;
	}

	// Decode every embedded image in parallel, then create the textures on the game thread.
	const TArray<TSharedPtr<FJsonValue>>& Images = Glb.Arr(TEXT("images"));
	TArray<FDecodedImage> Decoded;
	Decoded.SetNum(Images.Num());
	IImageWrapperModule& ImageModule = FModuleManager::LoadModuleChecked<IImageWrapperModule>(TEXT("ImageWrapper"));
	ParallelFor(Images.Num(), [&](int32 Index)
	{
		const TSharedPtr<FJsonObject> Img = Images[Index]->AsObject();
		const uint8* Data = nullptr;
		int64 Size = 0;
		if (Glb.View(static_cast<int32>(Img->GetNumberField(TEXT("bufferView"))), Data, Size))
		{
			DecodeImage(ImageModule, Data, Size, Decoded[Index]);
		}
	});
	TArray<UTexture2D*> ImageTextures;
	for (int32 Index = 0; Index < Decoded.Num(); Index++)
	{
		UTexture2D* Tex = Decoded[Index].Width > 0 ? MakeTexture(Decoded[Index], true, NAME_None) : nullptr;
		ImageTextures.Add(Tex);
		if (Tex)
		{
			Out.Owned.Add(Tex);
		}
	}
	TArray<int32> TextureSource;
	for (const TSharedPtr<FJsonValue>& V : Glb.Arr(TEXT("textures")))
	{
		TextureSource.Add(static_cast<int32>(V->AsObject()->GetNumberField(TEXT("source"))));
	}

	// Materials
	UMaterialInterface* BaseOpaque = LoadBaseMaterial(kMatOpaque);
	UMaterialInterface* BaseOpaque2S = LoadBaseMaterial(kMatOpaque2S);
	UMaterialInterface* BaseMasked = LoadBaseMaterial(kMatMasked);
	UMaterialInterface* BaseGlass = LoadBaseMaterial(kMatGlass);
	TArray<FMaterialDef> Defs;
	TArray<UMaterialInterface*> Mats;
	for (const TSharedPtr<FJsonValue>& V : Glb.Arr(TEXT("materials")))
	{
		const TSharedPtr<FJsonObject> M = V->AsObject();
		FMaterialDef D;
		D.Name = FName(*M->GetStringField(TEXT("name")));
		const TSharedPtr<FJsonObject>* Pbr = nullptr;
		if (M->TryGetObjectField(TEXT("pbrMetallicRoughness"), Pbr))
		{
			D.BaseColor = ReadColor(*Pbr, TEXT("baseColorFactor"), FLinearColor::White);
			D.Roughness = static_cast<float>((*Pbr)->GetNumberField(TEXT("roughnessFactor")));
			D.Metallic = static_cast<float>((*Pbr)->GetNumberField(TEXT("metallicFactor")));
			const TSharedPtr<FJsonObject>* TexInfo = nullptr;
			if ((*Pbr)->TryGetObjectField(TEXT("baseColorTexture"), TexInfo))
			{
				const int32 TexIndex = static_cast<int32>((*TexInfo)->GetNumberField(TEXT("index")));
				D.Texture = TextureSource.IsValidIndex(TexIndex) ? TextureSource[TexIndex] : INDEX_NONE;
			}
		}
		D.Emissive = ReadColor(M, TEXT("emissiveFactor"), FLinearColor::Black);
		M->TryGetStringField(TEXT("alphaMode"), D.AlphaMode);
		M->TryGetBoolField(TEXT("doubleSided"), D.bDoubleSided);

		UMaterialInterface* Base = D.AlphaMode == TEXT("BLEND") ? BaseGlass : D.AlphaMode == TEXT("MASK") ? BaseMasked : D.bDoubleSided ? BaseOpaque2S : BaseOpaque;
		UMaterialInstanceDynamic* Mid = UMaterialInstanceDynamic::Create(Base, Outer);
		Mid->SetVectorParameterValue(TEXT("BaseColorFactor"), D.BaseColor);
		Mid->SetScalarParameterValue(TEXT("Roughness"), D.Roughness);
		Mid->SetScalarParameterValue(TEXT("Metallic"), D.Metallic);
		Mid->SetVectorParameterValue(TEXT("Emissive"), D.Emissive);
		Mid->SetScalarParameterValue(TEXT("Opacity"), D.BaseColor.A);
		if (ImageTextures.IsValidIndex(D.Texture) && ImageTextures[D.Texture])
		{
			Mid->SetTextureParameterValue(TEXT("BaseColorTexture"), ImageTextures[D.Texture]);
		}
		Out.Materials.Add(D.Name, Mid);
		Out.Owned.Add(Mid);
		Defs.Add(D);
		Mats.Add(Mid);
	}

	// Meshes: the converter writes an "Exterior" and an "Interior" node.
	const TArray<TSharedPtr<FJsonValue>>& Meshes = Glb.Arr(TEXT("meshes"));
	for (const TSharedPtr<FJsonValue>& NodeV : Glb.Arr(TEXT("nodes")))
	{
		const TSharedPtr<FJsonObject> Node = NodeV->AsObject();
		int32 MeshIndex = INDEX_NONE;
		if (!Node->TryGetNumberField(TEXT("mesh"), MeshIndex) || !Meshes.IsValidIndex(MeshIndex))
		{
			continue;
		}
		const FString NodeName = Node->GetStringField(TEXT("name"));
		const FName MeshName = MakeUniqueObjectName(Outer, UStaticMesh::StaticClass(), FName(*FString::Printf(TEXT("%s_%s"), *Entry.Id, *NodeName)));
		UStaticMesh* Mesh = BuildMesh(Glb, Meshes[MeshIndex]->AsObject(), Mats, Defs, Outer, MeshName);
		if (!Mesh)
		{
			continue;
		}
		Out.Owned.Add(Mesh);
		if (NodeName == TEXT("Interior"))
		{
			Out.Interior = Mesh;
		}
		else
		{
			Out.Exterior = Mesh;
		}
	}
	if (!Out.Exterior)
	{
		OutError = TEXT("GLB has no exterior mesh");
		return false;
	}
	UE_LOG(LogSkyLine, Log, TEXT("Loaded %s: %d triangles, %d materials, %d textures in %.1f s"), *Entry.Id, Entry.Triangles,
		Mats.Num(), ImageTextures.Num(), FPlatformTime::Seconds() - T0);
	return true;
}

void FAircraftModelLoader::ApplyLivery(const FSkyLineAircraftEntry& Entry, const FSkyLineLivery& Livery, UObject* Outer, FSkyLineAircraftModel& Model)
{
	for (const FSkyLineLiverySlot& Slot : Entry.Slots)
	{
		const FString* Path = Livery.Textures.Find(Slot.Index);
		if (!Path)
		{
			continue;
		}
		UTexture2D* Tex = LoadTextureFile(*Path, true, Outer);
		if (!Tex)
		{
			continue;
		}
		Model.Owned.Add(Tex);
		for (const FName& MatName : Slot.Materials)
		{
			if (UMaterialInstanceDynamic** Mid = Model.Materials.Find(MatName))
			{
				(*Mid)->SetTextureParameterValue(TEXT("BaseColorTexture"), Tex);
			}
		}
	}
	UE_LOG(LogSkyLine, Log, TEXT("%s livery: %s (%s)"), *Entry.Id, *Livery.Name, *Livery.Registration);
}
