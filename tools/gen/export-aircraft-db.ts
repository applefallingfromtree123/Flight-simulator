// One-off generator: exports the legacy TypeScript aircraft database + flap schedules into C++.
// node --experimental-transform-types tools/gen/export-aircraft-db.ts > Unreal/.../Private/AircraftDb.cpp
import { AIRCRAFT } from '../../src/sim/aircraftDb.ts';
import { FLAP_SCHEDULES } from '../../src/sim/types.ts';
import { SPECS } from '../../src/sim/specs.ts';

const E = (prefix: string, v: string) => `${prefix}::${v.split(/[-_]/).map(s => s === 'ga' ? 'GA' : s[0].toUpperCase() + s.slice(1)).join('')}`;
const num = (v: number | undefined, d = 0) => { const x = v ?? d; return Number.isInteger(x) ? `${x}` : `${x}`; };
const s = (v: string) => JSON.stringify(v);
const cat = (c: string) => ({ ga: 'GA' } as Record<string, string>)[c] ?? c[0].toUpperCase() + c.slice(1);
const engT = (t: string) => ({ fan: 'Fan', jet: 'Jet', prop: 'Prop', tprop: 'TProp', shaft: 'Shaft', none: 'None' } as Record<string, string>)[t];
const mount = (m: string) => ({ wing: 'Wing', wing4: 'Wing4', aft: 'Aft', tri: 'Tri', nose: 'Nose', nacelle: 'Nacelle', nacelle4: 'Nacelle4', internal: 'Internal', internal2: 'Internal2', top: 'Top' } as Record<string, string>)[m];
const flaps = (f: string) => ({ boeing: 'Boeing', boeing747: 'Boeing747', airbus: 'Airbus', ga: 'GA', bizjet: 'Bizjet', regional: 'Regional', fighter: 'Fighter', none: 'None', split: 'Split' } as Record<string, string>)[f];
const cockpit = (c: string) => ({ airliner: 'Airliner', g1000: 'G1000', steam: 'Steam', fighter: 'Fighter', heli: 'Heli' } as Record<string, string>)[c];
const tail = (t: string) => ({ conv: 'Conv', T: 'T', cruciform: 'Cruciform', twin: 'Twin', H: 'H', delta: 'Delta' } as Record<string, string>)[t];
void E;

const out: string[] = [];
out.push('// GENERATED by tools/gen/export-aircraft-db.ts from the original SkyLine aircraft database. Do not edit by hand.');
out.push('#include "AircraftTypes.h"', '', 'namespace skyline {', '');
out.push('const std::vector<FlapDetent>& FlapDetents(FlapSchedule s) {');
for (const [k, v] of Object.entries(FLAP_SCHEDULES)) {
  out.push(`  static const std::vector<FlapDetent> k${flaps(k)} = {${v.map(f => `{${s(f.label)}, ${f.deg}, ${f.dCL}, ${f.dCLmax}, ${f.dCD}, ${f.dCm}}`).join(', ')}};`);
}
out.push('  switch (s) {');
for (const k of Object.keys(FLAP_SCHEDULES)) out.push(`    case FlapSchedule::${flaps(k)}: return k${flaps(k)};`);
out.push('  }', '  return kNone;', '}', '');
out.push('namespace {', 'std::vector<AircraftDef> BuildDb() {', '  std::vector<AircraftDef> db;', `  db.reserve(${AIRCRAFT.length});`);
for (const a of AIRCRAFT) {
  const sp = SPECS[a.id];
  out.push('  {', '    AircraftDef d;');
  out.push(`    d.Id = ${s(a.id)}; d.Name = ${s(a.name)}; d.Maker = ${s(a.mfr)}; d.Icao = ${s(a.icao)};`);
  out.push(`    d.Cat = Category::${cat(a.cat)}; d.Fdm = FdmKind::${a.fdm === 'rotor' ? 'Rotor' : 'Fixed'}; d.Fbw = FbwLaw::${a.fbw ? a.fbw[0].toUpperCase() + a.fbw.slice(1) : 'None'}; d.Cockpit = CockpitKind::${cockpit(a.cockpit)};`);
  out.push(`    d.Length = ${a.L}; d.Span = ${a.b}; d.Area = ${a.S}; d.Height = ${a.H}; d.Diameter = ${a.dia}; d.Sweep = ${a.sweep}; d.Dihedral = ${a.dih};`);
  out.push(`    d.Wing = WingPos::${a.wing[0].toUpperCase() + a.wing.slice(1)}; d.Tail = TailKind::${tail(a.tail)}; d.Canard = ${!!a.canard};`);
  const e = a.eng;
  out.push(`    d.Eng.T = EngineType::${engT(e.t)}; d.Eng.N = ${e.n}; d.Eng.P = ${e.p}; d.Eng.Ab = ${num(e.ab)}; d.Eng.Mount = EngineMount::${mount(e.mount)}; d.Eng.Bpr = ${num(e.bpr, 5)}; d.Eng.PropD = ${num(e.propD, e.t === 'tprop' ? 2.5 : 2)}; d.Eng.Blades = ${num(e.blades)};`);
  out.push(`    d.M = {${a.m.e}, ${a.m.mtow}, ${a.m.mlw}, ${a.m.fuel}, ${a.m.pay}};`);
  const v = a.v;
  out.push(`    d.V = {${v.vs0}, ${v.vs1}, ${v.vr}, ${v.vref}, ${v.vmo}, ${v.mmo}, ${v.vle}, ${v.vfe}, ${v.cruise}, ${v.cruiseFt}, ${v.ceil}, ${num(v.v2)}};`);
  out.push(`    d.Flaps = FlapSchedule::${flaps(a.flaps)};`);
  const g = a.gear;
  out.push(`    d.Gear.T = GearKind::${g.t[0].toUpperCase() + g.t.slice(1)}; d.Gear.Retract = ${!!g.retract}; d.Gear.Wheelbase = ${num(g.wb)}; d.Gear.Track = ${num(g.track)}; d.Gear.Height = ${num(g.gh)};`);
  if (a.rotor) out.push(`    d.Rotor.D = ${a.rotor.D}; d.Rotor.Blades = ${a.rotor.blades}; d.Rotor.Tail = RotorTail::${a.rotor.tail[0].toUpperCase() + a.rotor.tail.slice(1)};`);
  out.push(`    d.Apu = ${!!a.apu}; d.Spoilers = ${!!a.spoilers}; d.Reversers = ${!!a.reversers}; d.Seats = ${num(a.seats)};`);
  if (sp) out.push(`    d.EngineName = ${s(sp.engine)}; d.RangeKm = ${sp.rangeKm}; d.FirstFlight = ${sp.first};`);
  out.push('    db.push_back(d);', '  }');
}
out.push('  return db;', '}', '}  // namespace', '');
out.push('const std::vector<AircraftDef>& AllAircraft() {', '  static const std::vector<AircraftDef> kDb = BuildDb();', '  return kDb;', '}', '');
out.push('const AircraftDef* FindAircraft(const std::string& id) {', '  for (const AircraftDef& d : AllAircraft())', '    if (d.Id == id) return &d;', '  return nullptr;', '}', '');
out.push('const AircraftDef& GetAircraft(const std::string& id) {', '  const AircraftDef* d = FindAircraft(id);', '  return d ? *d : AllAircraft().front();', '}', '', '}  // namespace skyline', '');
console.log(out.join('\n'));
